#!/bin/sh
# scripts/check_keil_refs.sh <uvprojx>... - every <FilePath>, every directory of the first
# NON-EMPTY <IncludePath> (an empty element precedes it in these projects) and a custom scatter
# file must exist relative to the project's MDK-ARM directory. Exit 1 on any missing item.
rc=0
for p in "$@"; do
    d=$(dirname "$p"); tot=0; miss=0; itot=0; imiss=0
    for f in $(grep -o '<FilePath>[^<]*</FilePath>' "$p" | sed 's/<[^>]*>//g' | tr '\\' '/'); do
        tot=$((tot + 1)); [ -f "$d/$f" ] || { miss=$((miss + 1)); echo "  MISSING file: $f"; }
    done
    for i in $(grep -o '<IncludePath>[^<][^<]*</IncludePath>' "$p" | head -1 | sed 's/<[^>]*>//g' | tr ';' ' ' | tr '\\' '/'); do
        itot=$((itot + 1)); [ -d "$d/$i" ] || { imiss=$((imiss + 1)); echo "  MISSING include dir: $i"; }
    done
    umf=$(grep -o '<umfTarg>[0-9]</umfTarg>' "$p" | sed 's/<[^>]*>//g' | head -1)
    sct=$(grep -o '<ScatterFile>[^<]*</ScatterFile>' "$p" | sed 's/<[^>]*>//g' | head -1)
    if [ "$umf" = "1" ]; then s="generated by uVision (umfTarg=1)"; elif [ -f "$d/$sct" ]; then s="custom $sct present"; else s="custom $sct MISSING"; miss=$((miss + 1)); fi
    echo "$(basename "$p"): files $tot referenced / $miss missing; include dirs $itot / $imiss missing; scatter: $s"
    [ $((miss + imiss)) -eq 0 ] || rc=1
done
exit $rc
